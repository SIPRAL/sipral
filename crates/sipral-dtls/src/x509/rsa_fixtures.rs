//! kept: for each size, `genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:N`,
//! `req -x509 -new -subj /CN=sipral-rsa-N -days 36500 -sha256 -outform DER`
//! over that key, and, for the two sizes this crate accepts, `dgst -sha256
//! -sign` over [`MESSAGE`], which is RSASSA-PKCS1-v1_5. The private keys were
//! discarded.

